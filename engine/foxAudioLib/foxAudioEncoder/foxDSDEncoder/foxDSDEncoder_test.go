func TestInterpolatorKeepsFramesAndRejectsImages(t *testing.T) {
	for _, L := range []int{2, 8, 16, 64} {
		r := 352800.0
		frames := 1 << 14
		x := make([]float64, frames)
		for i := range x {
			x[i] = 0.5*math.Sin(2*math.Pi*20000*float64(i)/r) + 0.25*math.Sin(2*math.Pi*80000*float64(i)/r)
		}
		it := newInterpolator(L)
		var out []float64
		for i := 0; i < frames; i += 1000 { // uneven pushes
			out = it.push(x[i:min(i+1000, frames)], out)
		}
		out = it.flush(out)
		if len(out) != frames*L {
			t.Fatalf("L %d: %d samples for %d frames", L, len(out), frames)
		}
		for k := range x {
			if out[k*L] != x[k] {
				t.Fatalf("L %d: sample %d is %v, frame %d was %v", L, k*L, out[k*L], k, x[k])
			}
		}
		// against the tones themselves at the output rate, away from both ends: images and passband error
		worst := 0.0
		for i := 64 * L; i < len(out)-64*L; i++ {
			tm := float64(i) / (r * float64(L))
			want := 0.5*math.Sin(2*math.Pi*20000*tm) + 0.25*math.Sin(2*math.Pi*80000*tm)
			worst = math.Max(worst, math.Abs(out[i]-want))
		}
		if db := 20 * math.Log10(worst); db > -100 {
			t.Errorf("L %d: worst error against the tones %.1f dBFS", L, db)
		}
	}
}

