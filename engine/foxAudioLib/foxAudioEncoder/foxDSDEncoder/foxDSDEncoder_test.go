func encode(t *testing.T, e *Encoder, x [][]float64, chunk int) []byte {
	t.Helper()
	if err := e.Open(); err != nil {
		t.Fatal(err)
	}
	h, _ := e.EncodeHeader()
	out := append([]byte(nil), h...)
	for i := 0; i < len(x[0]); i += chunk {
		part := make([][]float64, len(x))
		for c := range x {
			part[c] = x[c][i:min(i+chunk, len(x[c]))]
		}
		b, err := e.EncodeData(part)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, b...)
	}
	b, err := e.Close()
	if err != nil {
		t.Fatal(err)
	}
	return append(out, b...)
}

func stereoTone(frames int, rate, f, amp float64) [][]float64 {
	x := [][]float64{make([]float64, frames), make([]float64, frames)}
	for i := 0; i < frames; i++ {
		x[0][i] = amp * math.Sin(2*math.Pi*f*float64(i)/rate)
		x[1][i] = -0.5 * x[0][i]
	}
	return x
}

