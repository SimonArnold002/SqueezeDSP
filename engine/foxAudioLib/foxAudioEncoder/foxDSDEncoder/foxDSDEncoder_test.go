// hold skips a pass only when no output can pass the limit. A history set against one phase's taps at the limit,
// then silence, overshoots on the history alone, so the skip has to look back over it; and every pass, skipped or
// scanned, gives exactly what a full scan of the interpolator's output gives (random levels and chunk sizes).
func TestHoldBound(t *testing.T) {
	rng := rand.New(rand.NewSource(3))
	clamp := func(v []float64, lim float64) []float64 {
		out := append([]float64(nil), v...)
		for i, x := range out {
			out[i] = math.Max(-lim, math.Min(lim, x))
		}
		return out
	}
	for _, src := range sources {
		in, lim := 352800, Limit
		if src == "pcm" {
			in, lim = 705600, LimitPCM
		}
		for _, dsd := range []int{DSD64, 2 * DSD64, 8 * DSD64} {
			e := &Encoder{DSDRate: dsd, InRate: in, NumChannels: 1, Frames: 1 << 30, Source: src}
			if err := e.Open(); err != nil {
				t.Fatal(err)
			}
			ch, twin := e.chans[0], newInterpolator(e.L)
			K, l0, best := ch.it.K, 1, 0.0
			for l := 1; l < ch.it.L; l++ {
				sum := 0.0
				for _, h := range ch.it.h[l][:2*K] {
					sum += math.Abs(h)
				}
				if sum > best {
					best, l0 = sum, l
				}
			}
			pattern := make([]float64, 2*K) // a window's first 2K samples, each at the limit with its tap's sign
			for i, h := range ch.it.h[l0][:2*K] {
				pattern[i] = math.Copysign(lim, h)
			}
			if got, want := e.interpolate(ch, pattern, false, nil), clamp(twin.push(pattern, nil), lim); !slices.Equal(got, want) {
				t.Fatalf("%s %d: the pattern's own pass differs from a full scan", src, dsd)
			}
			raw := twin.push(make([]float64, 5), nil)
			if top := slices.Max(raw); top <= lim {
				t.Fatalf("%s %d: the pattern did not overshoot (%.4f): the test proves nothing", src, dsd, top)
			}
			over := ch.over
			got := e.interpolate(ch, make([]float64, 5), false, nil)
			if !slices.Equal(got, clamp(raw, lim)) || ch.over == over {
				t.Fatalf("%s %d: silence after a history at the limit: %.4f out, %d held (want %.4f, held)", src, dsd,
					slices.Max(got), ch.over-over, lim)
			}
			// the same pattern just under the limit, scaled so the interpolator lifts it 2% past: every input below
			// the limit, an output above it, so only the gain bound knows to scan
			if best < 1.05 {
				t.Fatalf("%s %d: the largest phase gain is %.3f: too small to test under the limit", src, dsd, best)
			}
			e2 := &Encoder{DSDRate: dsd, InRate: in, NumChannels: 1, Frames: 1 << 30, Source: src}
			if err := e2.Open(); err != nil {
				t.Fatal(err)
			}
			ch2, twin2 := e2.chans[0], newInterpolator(e2.L)
			under := make([]float64, len(pattern))
			for i, v := range pattern {
				under[i] = v * 1.02 / best
			}
			e2.interpolate(ch2, under, false, nil)
			twin2.push(under, nil)
			raw = twin2.push(make([]float64, 5), nil)
			if top := slices.Max(raw); top <= lim || slices.Max(under) >= lim {
				t.Fatalf("%s %d: under the limit (%.4f in) the pattern gave %.4f: the test proves nothing", src, dsd, slices.Max(under), top)
			}
			if got := e2.interpolate(ch2, make([]float64, 5), false, nil); !slices.Equal(got, clamp(raw, lim)) {
				t.Fatalf("%s %d: silence after a history just under the limit: %.4f out (want %.4f)", src, dsd, slices.Max(got), lim)
			}
			for pass := 0; pass < 200; pass++ {
				x := make([]float64, 1+rng.Intn(300))
				level := lim * (0.5 + 0.6*rng.Float64()) // some passes reach the limit, some cannot
				for i := range x {
					x[i] = level * math.Sin(2*math.Pi*rng.Float64())
				}
				got := e.interpolate(ch, x, false, nil)
				if want := clamp(twin.push(clamp(x, lim), nil), lim); !slices.Equal(got, want) {
					t.Fatalf("%s %d, pass %d (level %.3f): differs from a full scan", src, dsd, pass, level)
				}
			}
			if got, want := e.interpolate(ch, nil, true, nil), clamp(twin.flush(nil), lim); !slices.Equal(got, want) {
				t.Fatalf("%s %d: the flush differs from a full scan", src, dsd)
			}
		}
	}
}

// pack, a whole byte's eight bits at once, gives the bytes packing bit by bit gives (oldest in the LSB), however the
// bits arrive: runs that start mid-byte, short runs, block ends, the stated count stopping it.
func TestPackMatchesBits(t *testing.T) {
	rng := rand.New(rand.NewSource(7))
	n := 3*blockSize*8 + 13
	bits := make([]byte, n)
	for i := range bits {
		bits[i] = byte(rng.Intn(2))
	}
	e := &Encoder{count: int64(n - 5)}
	ch := &channel{block: make([]byte, blockSize)}
	for i := 0; i < n; {
		k := min(n-i, 1+rng.Intn(40))
		e.pack(ch, bits[i:i+k])
		i += k
	}
	var want []byte
	var cur byte
	var nb uint
	for _, b := range bits[:n-5] {
		cur |= b << nb
		if nb++; nb == 8 {
			want = append(want, cur)
			cur, nb = 0, 0
		}
	}
	var got []byte
	for _, b := range ch.full {
		got = append(got, b...)
	}
	got = append(got, ch.block[:ch.pos]...)
	if !bytes.Equal(got, want) || ch.cur != cur || ch.nbit != nb || ch.done != int64(n-5) {
		t.Fatalf("packed %d bytes (%d wanted), first difference %d; cur %#x/%#x, %d/%d bits, done %d", len(got), len(want),
			func() int {
				for i := range min(len(got), len(want)) {
					if got[i] != want[i] {
						return i
					}
				}
				return -1
			}(), ch.cur, cur, ch.nbit, nb, ch.done)
	}
}

