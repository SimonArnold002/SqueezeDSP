// After a loud passage the safe design stays for the hold (and comes in the look-ahead before it); a passage just
// over the threshold (0.55: over the quiet design's own limit) brings it in too, and nothing runs away.
func TestAdaptiveHoldsAfterLoud(t *testing.T) {
	rate := 2822400.0
	n := int(rate * 0.5)
	for _, amp := range []float64{0.72, 0.55} {
		u := make([]float64, n)
		b0, b1 := int(rate*0.2), int(rate*0.21) // a 10 ms passage at amp, quiet (0.1) around it
		for i := range u {
			a := 0.1
			if i >= b0 && i < b1 {
				a = amp
			}
			u[i] = a * math.Sin(2*math.Pi*1000*float64(i)/rate)
		}
		l := newAdaptiveLoop(adaptiveDesigns[0], adaptiveDesigns[1], int(rate))
		l.drain(l.run(u, nil))
		// in from the look-ahead before the passage, out after the hold and the fade down
		want := float64(int64(adaptAheadSec*rate) + int64(b1-b0) + int64(adaptHoldSec*rate) + int64(adaptRampSec*rate))
		if got := float64(l.samplesInB); l.resets != 0 || math.Abs(got-want) > 0.05*want {
			t.Errorf("%.2f for 10 ms: %d resets, %.0f samples on the safe design, want about %.0f", amp, l.resets, got, want)
		}
	}
}

// Source (0.1.72.33): a PCM source gets designsPCM, held at LimitPCM; a DSD source (or none given) designs, held at
// Limit; anything else refused. Through Open, then through the samples: 1 kHz at 0.7 from 705.6k is held at 0.63
// for a PCM source and untouched for a DSD source, with no runaway either way.
func TestSourceChoosesDesigns(t *testing.T) {
	for _, tc := range []struct {
		src   string
		table map[string][2][5]section
		limit float64
	}{{"", designs, Limit}, {"dsd", designs, Limit}, {"pcm", designsPCM, LimitPCM}} {
		for _, kind := range []string{"standard", "clans"} {
			for fam, rate := range []int{DSD64, 4 * DSD64} {
				e := &Encoder{DSDRate: rate, InRate: 705600, NumChannels: 2, Frames: 70560, Kind: kind, Source: tc.src}
				if err := e.Open(); err != nil {
					t.Fatal(err)
				}
				want, got := newModulator(tc.table[kind][fam]), e.chans[0].mod
				if got.d1 != want.d1 || got.d2 != want.d2 || got.a1 != want.a1 || got.a2 != want.a2 || e.limit != tc.limit {
					t.Errorf("source %q, %s DSD%d: not its designs, or limit %.2f (want %.2f)", tc.src, kind, rate/44100, e.limit, tc.limit)
				}
			}
		}
	}
	if err := (&Encoder{DSDRate: DSD64, InRate: 705600, NumChannels: 2, Frames: 1000, Source: "sacd"}).Open(); err == nil {
		t.Error(`source "sacd": taken`)
	}
	x := make([]float64, 70560)
	for i := range x {
		x[i] = 0.7 * math.Sin(2*math.Pi*1000*float64(i)/705600)
	}
	for _, tc := range []struct {
		src     string
		limited bool
	}{{"pcm", true}, {"dsd", false}} {
		e := &Encoder{DSDRate: DSD64, InRate: 705600, NumChannels: 2, Frames: int64(len(x)), Source: tc.src}
		encode(t, e, [][]float64{x, x}, 1<<15)
		if (e.Limited > 0) != tc.limited || e.Resets != 0 || math.Abs(e.Peak-0.7) > 0.001 {
			t.Errorf("source %s, 1 kHz at 0.7: peak %.4f, %d limited, %d resets (held: %v)", tc.src, e.Peak, e.Limited, e.Resets, tc.limited)
		}
	}
}

// The interpolator's overshoot is held at the limit too (hold): a jump to the limit from silence, and 1 kHz at the limit
// from its peak (a seek into a loud passage), stereo as the spec bench runs them, 2 s, at DSD512 from 352.8k: no runaway,
// the overshoot counted. Without hold, order 7 standard ran away twice on each (2026-11-04 bench).
func TestOvershootHeld(t *testing.T) {
	for _, src := range sources {
		in, lim := 352800, Limit
		if src == "pcm" {
			in, lim = 705600, LimitPCM
		}
		for _, kind := range []string{"standard", "clans"} {
			for _, ph := range []float64{-1, math.Pi / 2} {
				x := [][]float64{make([]float64, 2*in), make([]float64, 2*in)}
				for i := range x[0] {
					x[0][i] = lim
					if ph >= 0 {
						x[0][i] = lim * math.Sin(2*math.Pi*1000*float64(i)/float64(in)+ph)
					}
					x[1][i] = -x[0][i]
				}
				e := &Encoder{DSDRate: 8 * DSD64, InRate: in, NumChannels: 2, Frames: int64(2 * in), Kind: kind, Source: src}
				encode(t, e, x, 1<<15)
				if e.Resets != 0 || e.Overshoot == 0 {
					t.Errorf("%s %s, %s at the limit: %d resets, %d held after the interpolator", src, kind,
						map[bool]string{true: "a DC jump", false: "1 kHz from its peak"}[ph < 0], e.Resets, e.Overshoot)
				}
			}
		}
	}
}
