func TestLegendreRoots(t *testing.T) {
	for n := 1; n <= 12; n++ {
		r := legendreRoots(n)
		if len(r) != n {
			t.Fatalf("order %d: %d roots", n, len(r))
		}
		for i, x := range r {
			p0, p1 := 1.0, x
			for k := 2; k <= n; k++ {
				p0, p1 = p1, ((2*float64(k)-1)*x*p1-(float64(k)-1)*p0)/float64(k)
			}
			if math.Abs(p1) > 1e-12 || math.Abs(x+r[n-1-i]) > 1e-12 {
				t.Fatalf("order %d root %d = %v: P = %v, not symmetric", n, i, x, p1)
			}
		}
	}
}

func TestStandardMeetsItsGain(t *testing.T) {
	for _, obg := range []float64{1.25, 1.28, 1.5} {
		f := designStandard(order, 2*math.Pi*20000/2822400, obg)
		if g := gainAt(f.zeros, f.poles, math.Pi); math.Abs(g-obg) > 1e-9 {
			t.Fatalf("gain at half the rate %v, asked %v", g, obg)
		}
		if g := f.maxGain(); g > obg*(1+1e-9) {
			t.Fatalf("largest gain %v over %v: a peak somewhere", g, obg)
		}
		for _, p := range f.poles {
			if cmplx.Abs(p) >= 1 {
				t.Fatalf("pole %v outside the unit circle", p)
			}
		}
	}
}

// The tables are what the design code makes (within float rounding: a CLANS search on another machine can
// end a hair away), and each table's sum of |h| keeps to its cap.
func TestTablesMatchDesign(t *testing.T) {
	for _, src := range sources {
		for _, kind := range []string{"standard", "clans"} {
			for fam := 0; fam < 2; fam++ {
				got := tableFor(src)[kind][fam]
				want := five(designFor(src, kind, fam).sections())
				p := params[src][kind][fam]
				wB := 2 * math.Pi * families[fam].band / families[fam].rate
				if d := math.Abs(inBandDB(got, wB) - inBandDB(want, wB)); d > 0.5 {
					t.Errorf("%s %s %d: in-band share %.2f dB, the design code's %.2f", src, kind, fam, inBandDB(got, wB), inBandDB(want, wB))
				}
				if d := math.Abs(maxGainOf(got) - maxGainOf(want)); d > 1e-3 {
					t.Errorf("%s %s %d: max gain %.4f, the design code's %.4f", src, kind, fam, maxGainOf(got), maxGainOf(want))
				}
				if kind == "clans" && l1(got[:], 3000) > p+1e-3 {
					t.Errorf("%s clans %d: impulse sum %.4f over the cap %.2f", src, fam, l1(got[:], 3000), p)
				}
				if kind == "standard" && math.Abs(maxGainOf(got)-p) > 1e-6 {
					t.Errorf("%s standard %d: max gain %.6f, not %.2f", src, fam, maxGainOf(got), p)
				}
			}
		}
	}
	wB := 2 * math.Pi * families[0].band / families[0].rate
	for i := 0; i < 2; i++ {
		want := adaptiveDesign(i)
		got, ws := adaptiveDesigns[i], four(want.sections())
		var g5, w5 [5]section
		copy(g5[:], got[:])
		copy(w5[:], ws[:])
		g5[4], w5[4] = section{}, section{} // a zero section is 1: the response is the four's
		if d := math.Abs(inBandDB(g5, wB) - inBandDB(w5, wB)); d > 0.5 {
			t.Errorf("adaptive %d: in-band share %.2f dB, the design code's %.2f", i, inBandDB(g5, wB), inBandDB(w5, wB))
		}
		if d := math.Abs(maxGainOf(g5) - maxGainOf(w5)); d > 1e-3 {
			t.Errorf("adaptive %d: max gain %.4f, the design code's %.4f", i, maxGainOf(g5), maxGainOf(w5))
		}
	}
	if math.Abs(maxGainOf([5]section{adaptiveDesigns[0][0], adaptiveDesigns[0][1], adaptiveDesigns[0][2], adaptiveDesigns[0][3]})-adaptQuietOBG) > 1e-6 {
		t.Error("adaptive quiet design: max gain is not 1.45")
	}
	if l1(adaptiveDesigns[1][:], 3000) > adaptSafeCap+1e-3 {
		t.Errorf("adaptive safe design: impulse sum %.4f over %.2f", l1(adaptiveDesigns[1][:], 3000), adaptSafeCap)
	}
}

