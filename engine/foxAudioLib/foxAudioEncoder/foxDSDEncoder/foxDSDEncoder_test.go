// inBandSTFT: the in-band power of (y - u) per window of n samples (Hann, half overlap), dB re a full-scale sine.
func inBandSTFT(y, u []float64, rate float64, n int) []float64 {
	var out []float64
	w := make([]float64, n)
	ws := 0.0
	for i := range w {
		w[i] = 0.5 - 0.5*math.Cos(2*math.Pi*float64(i)/float64(n))
		ws += w[i] * w[i]
	}
	a := make([]complex128, n)
	for s := 0; s+n <= len(y); s += n / 2 {
		for i := 0; i < n; i++ {
			a[i] = complex((y[s+i]-u[s+i])*w[i], 0)
		}
		fft(a)
		df := rate / float64(n)
		sum := 0.0
		for k := int(20 / df); k <= int(20000/df); k++ {
			m := cmplx.Abs(a[k])
			sum += 2 * m * m
		}
		out = append(out, 10*math.Log10(sum/(float64(n)*ws)/0.5+1e-300))
	}
	return out
}

// bursts: 1 kHz at 0.3 for 200 ms then at 0.72 for 100 ms, repeated, and a 20 Hz passage at 0.72 (2.4-2.6 s)
func bursts(rate float64, secs float64) []float64 {
	u := make([]float64, int(rate*secs))
	for t := range u {
		s := float64(t) / rate
		amp := 0.3
		if math.Mod(s, 0.3) >= 0.2 {
			amp = 0.72
		}
		u[t] = amp * math.Sin(2*math.Pi*1000*s)
		if s > 2.4 && s < 2.6 {
			u[t] = 0.72 * math.Sin(2*math.Pi*20*s)
		}
	}
	return u
}

// Over bursts the adaptive loop never runs away (its quiet design alone does, at 0.72), takes the safe design for
// every loud passage, and a fade adds nothing in band: no 2.9 ms window holding one is noisier than the loud
// passages themselves (a hard switch put -55 dB there). Fed in odd-sized pieces: the look-ahead spans them.
func TestAdaptiveBursts(t *testing.T) {
	rate := 2822400.0
	u := bursts(rate, 3)
	l := newAdaptiveLoop(adaptiveDesigns[0], adaptiveDesigns[1], int(rate))
	var bits []byte
	for i := 0; i < len(u); i += 50000 {
		bits = l.run(u[i:min(i+50000, len(u))], bits)
	}
	bits = l.drain(bits)
	if len(bits) != len(u) || l.resets != 0 {
		t.Fatalf("%d bits for %d samples, %d resets", len(bits), len(u), l.resets)
	}
	if r := runsAny(adaptiveDesigns[0][:], rate, 1000, 0.72, 0.5); r == 0 {
		t.Fatal("control: the quiet design alone did not run away at 0.72")
	}
	// the safe design's share: every loud passage (100 ms of 300, and 2.4-2.6 s), each with look-ahead and hold
	if share := float64(l.samplesInB) / float64(len(u)); share < 0.3 || share > 0.75 {
		t.Errorf("on the safe design %.0f%% of the time", share*100)
	}
	st := inBandSTFT(bitsToFloat(bits), u, rate, 8192)
	// classify windows by the blend: none of B, all of B, or a fade within
	mode := make([]float64, len(u))
	{
		m := newAdaptiveLoop(adaptiveDesigns[0], adaptiveDesigns[1], int(rate))
		m.receive(u)
		for k := range u { // replay the decisions only
			idx := int64(k)
			if m.nl[k]-idx <= m.ahead {
				m.inB, m.left = true, m.hold
			} else if m.inB {
				if m.left > 0 {
					m.left--
				} else {
					m.inB = false
				}
			}
			if m.inB {
				m.alpha = math.Min(1, m.alpha+m.step)
			} else {
				m.alpha = math.Max(0, m.alpha-m.step)
			}
			mode[k] = m.alpha
		}
	}
	worstLoud, worstFade := -400.0, -400.0
	for i, v := range st {
		s0, s1 := i*4096, i*4096+8192
		if s0 < int(rate*0.05) {
			continue
		}
		lo, hi := 2.0, -1.0
		for t := s0; t < s1; t += 16 {
			lo, hi = math.Min(lo, mode[t]), math.Max(hi, mode[t])
		}
		switch {
		case lo == 1:
			worstLoud = math.Max(worstLoud, v)
		case hi > lo:
			worstFade = math.Max(worstFade, v)
		}
	}
	if worstFade > worstLoud+3 || worstFade > -105 {
		t.Errorf("windows with a fade reach %.1f dB in band, loud passages %.1f", worstFade, worstLoud)
	}
}

// Quiet input never leaves the quiet design, and its noise is that design's.
func TestAdaptiveQuietIsQuiet(t *testing.T) {
	rate := 2822400.0
	n := 1 << 21
	settle := int(rate * 0.05)
	u := make([]float64, n+settle)
	for i := range u {
		u[i] = 0.3 * math.Sin(2*math.Pi*1000*float64(i)/rate)
	}
	l := newAdaptiveLoop(adaptiveDesigns[0], adaptiveDesigns[1], int(rate))
	bits := l.drain(l.run(u, nil))
	if l.samplesInB != 0 || l.resets != 0 {
		t.Fatalf("%d samples on the safe design, %d resets, for a quiet input", l.samplesInB, l.resets)
	}
	sp := spectrumOf(bitsToFloat(bits[settle:settle+n]), rate)
	if lv := sp.tone(1000); math.Abs(lv-20*math.Log10(0.3)) > 0.005 {
		t.Errorf("tone %.4f dBFS", lv)
	}
	// bench 2026-11-02 (0.3, order 7 at 1.45): in band -144.6, 20-50 kHz -58.8; 3 dB to spare
	if nb, nu := sp.band(20, 20000, 1000), sp.band(20000, 50000, 1000); nb > -141.6 || nu > -55.8 {
		t.Errorf("noise in band %.1f, 20-50 kHz %.1f dBFS", nb, nu)
	}
}

// Above DSD64, adaptive is the standard modulator, bit for bit; at DSD64 it is neither plain design.
