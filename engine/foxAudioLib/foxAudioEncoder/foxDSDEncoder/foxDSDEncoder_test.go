var update = flag.Bool("update", false, "rewrite tables.go from the design code")

// The designs the engine runs: order 7 at every rate (Simon 2026-11-04: "Look at 7th order for all"), by the
// source (ledger ORDER 7 SWEEP): a DSD source's stable to 0.75 and held at Limit (0.72); a PCM source's, which
// comes in at -6.02 dB (peaks 0.5), stable to 0.65 and held at LimitPCM (0.63). Standard by its out-of-band
// gain, CLANS by its impulse-response sum (params). DSD64 with a 20 kHz band, DSD128 and up with 30 kHz at
// DSD128 (the band scales with the rate, so one design).
var families = [2]struct{ rate, band float64 }{{2822400, 20000}, {5644800, 30000}}

// params[source][kind][family]: standard's out-of-band gain, CLANS's cap on the impulse sum
var params = map[string]map[string][2]float64{
	"dsd": {"standard": {1.28, 1.28}, "clans": {2.90, 2.70}},
	"pcm": {"standard": {1.35, 1.35}, "clans": {3.10, 2.90}},
}

var sources = []string{"dsd", "pcm"}

const (
	order       = 7
	clansRmax   = 0.99
	stableTo    = 0.75 // TestGenerateTables refuses a DSD source's design that runs away below this
	stableToPCM = 0.64 // ... and a PCM source's
	// the adaptive modulator's pair, DSD64, order 7 (2026-11-02 bench): quiet = standard at 1.45 (stable to about
	// 0.52), safe = CLANS at a cap of 2.9 (stable to 0.75)
	adaptOrder    = 7
	adaptQuietOBG = 1.45
	adaptSafeCap  = 2.9
	quietStableTo = 0.50
)

func adaptiveDesign(i int) ntf {
	wB := 2 * math.Pi * families[0].band / families[0].rate
	if i == 1 {
		return designCLANS(adaptOrder, wB, adaptSafeCap, clansRmax)
	}
	return designStandard(adaptOrder, wB, adaptQuietOBG)
}

func four(s []section) [4]section {
	var out [4]section
	copy(out[:], s)
	return out
}

// runsAny: the plain error-feedback loop for any number of sections (a check, not the engine's loop)
func runsAny(secs []section, rate, f, amp, secsLong float64) int64 {
	n := len(secs)
	w1, w2, c := make([]float64, n), make([]float64, n), make([]float64, n)
	var resets int64
	for i := 0; i < int(secsLong*rate); i++ {
		x := amp
		if f > 0 {
			x = amp * math.Sin(2*math.Pi*f*float64(i)/rate)
		}
		v := x
		for k, s := range secs {
			c[k] = (s.b1-s.a1)*w1[k] + (s.b2-s.a2)*w2[k]
			v += c[k]
		}
		if math.Abs(v) > guard {
			clear(w1)
			clear(w2)
			clear(c)
			v = x
			resets++
		}
		y := -1.0
		if v >= 0 {
			y = 1
		}
		in := y - v
		for k, s := range secs {
			w0 := in - s.a1*w1[k] - s.a2*w2[k]
			w2[k], w1[k] = w1[k], w0
			in += c[k]
		}
	}
	return resets
}

// design: a DSD source's; designFor: either source's.
func design(kind string, fam int) ntf { return designFor("dsd", kind, fam) }

func designFor(src, kind string, fam int) ntf {
	wB := 2 * math.Pi * families[fam].band / families[fam].rate
	if kind == "clans" {
		return designCLANS(order, wB, params[src][kind][fam], clansRmax)
	}
	return designStandard(order, wB, params[src][kind][fam])
}

func tableFor(src string) map[string][2][5]section {
	if src == "pcm" {
		return designsPCM
	}
	return designs
}

func limitFor(src string) float64 {
	if src == "pcm" {
		return LimitPCM
	}
	return Limit
}

// response: |H| from the sections themselves
func response(secs [5]section, w float64) float64 {
	z1 := cmplx.Exp(complex(0, -w))
	z2 := z1 * z1
	g := 1.0
	for _, s := range secs {
		g *= cmplx.Abs(1+complex(s.b1, 0)*z1+complex(s.b2, 0)*z2) / cmplx.Abs(1+complex(s.a1, 0)*z1+complex(s.a2, 0)*z2)
	}
	return g
}

func inBandDB(secs [5]section, wB float64) float64 {
	const m = 400
	s := 0.0
	for i := 0; i < m; i++ {
		g := response(secs, wB*(float64(i)+0.5)/m)
		s += g * g
	}
	return 10 * math.Log10(s*wB/m/math.Pi)
}

func maxGainOf(secs [5]section) float64 {
	m := 0.0
	for i := 0; i <= 4096; i++ {
		m = math.Max(m, response(secs, math.Pi*float64(i)/4096))
	}
	return m
}

func five(s []section) [5]section {
	var out [5]section
	copy(out[:], s)
	return out
}

// runs: a sine of amp at f (0: DC) through the loop for secs; the resets and the bits
func runs(secs [5]section, rate, f, amp, secsLong float64) (int64, []byte) {
	m := newModulator(secs)
	n := int(secsLong * rate)
	u := make([]float64, n)
	for i := range u {
		if f == 0 {
			u[i] = amp
		} else {
			u[i] = amp * math.Sin(2*math.Pi*f*float64(i)/rate)
		}
	}
	bits := make([]byte, n)
	m.run(u, bits)
	return m.resets, bits
}

