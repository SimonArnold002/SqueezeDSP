type spectrum struct {
	p        []float64
	df, enbw float64
	lobe     int
}

// spectrumOf: Kaiser beta 30, levels so a full-scale sine reads 0 dB (as the decoder bench's dsdana)
func spectrumOf(x []float64, rate float64) spectrum {
	n := len(x)
	a := make([]complex128, n)
	beta := 30.0
	ws, s2 := 0.0, 0.0
	for i := range x {
		r := 2*float64(i)/float64(n-1) - 1
		w := bessel0(beta*math.Sqrt(math.Max(0, 1-r*r))) / bessel0(beta)
		ws += w
		s2 += w * w
		a[i] = complex(x[i]*w, 0)
	}
	fft(a)
	p := make([]float64, n/2)
	for i := range p {
		m := cmplx.Abs(a[i]) * 2 / ws
		p[i] = m * m / 2
	}
	return spectrum{p: p, df: rate / float64(n), enbw: float64(n) * s2 / (ws * ws), lobe: int(math.Ceil(beta/math.Pi)) + 2}
}

func fft(a []complex128) {
	n := len(a)
	for i, j := 1, 0; i < n; i++ {
		bit := n >> 1
		for ; j&bit != 0; bit >>= 1 {
			j ^= bit
		}
		j ^= bit
		if i < j {
			a[i], a[j] = a[j], a[i]
		}
	}
	for l := 2; l <= n; l <<= 1 {
		for k := 0; k < l/2; k++ {
			wk := cmplx.Exp(complex(0, -2*math.Pi*float64(k)/float64(l)))
			for i := k; i < n; i += l {
				u, v := a[i], a[i+l/2]*wk
				a[i], a[i+l/2] = u+v, u-v
			}
		}
	}
}

func (s spectrum) band(lo, hi, tone float64) float64 {
	tb := int(math.Round(tone / s.df))
	sum := 0.0
	for i := max(2, int(lo/s.df)); i <= int(hi/s.df) && i < len(s.p); i++ {
		if i >= tb-s.lobe && i <= tb+s.lobe {
			continue
		}
		sum += s.p[i]
	}
	return 10 * math.Log10(sum/s.enbw*2+1e-300)
}

func (s spectrum) tone(f float64) float64 {
	tb := int(math.Round(f / s.df))
	sum := 0.0
	for i := max(0, tb-s.lobe); i <= tb+s.lobe; i++ {
		sum += s.p[i]
	}
	return 10 * math.Log10(sum/s.enbw*2)
}

func bitsToFloat(b []byte) []float64 {
	x := make([]float64, len(b))
	for i, v := range b {
		x[i] = float64(v)*2 - 1
	}
	return x
}

// The level is unity and the noise in 20 Hz-20 kHz is what the sweep measured (ledger ORDER 7 SWEEP, 1 kHz at
// 0.5, 2^22 points: a DSD source's standard -123.7 / -143.3 dBFS and CLANS -127.6 / -147.5 at DSD64 / DSD128; a
// PCM source's standard -133.7 / -154.4, CLANS -142.0 / -160.3), with 3 dB to spare.
func TestLoopLevelAndNoise(t *testing.T) {
	limits := map[string]map[string][2]float64{
		"dsd": {"standard": {-120.7, -140.3}, "clans": {-124.6, -144.5}},
		"pcm": {"standard": {-130.7, -151.4}, "clans": {-139.0, -157.3}},
	}
	for _, src := range sources {
		for _, kind := range []string{"standard", "clans"} {
			for fam := 0; fam < 2; fam++ {
				rate := families[fam].rate
				n := 1 << 21
				settle := int(rate * 0.02)
				_, bits := runs(tableFor(src)[kind][fam], rate, 1000, 0.5, float64(n+settle)/rate)
				s := spectrumOf(bitsToFloat(bits[settle:settle+n]), rate)
				if lv := s.tone(1000); math.Abs(lv-(-6.0206)) > 0.005 {
					t.Errorf("%s %s %d: tone %.4f dBFS, want -6.0206", src, kind, fam, lv)
				}
				nb := s.band(20, 20000, 1000)
				t.Logf("%s %s %d: noise 20 Hz-20 kHz %.1f dBFS", src, kind, fam, nb)
				if nb > limits[src][kind][fam] {
					t.Errorf("%s %s %d: noise 20 Hz-20 kHz %.1f dBFS, over %.1f", src, kind, fam, nb, limits[src][kind][fam])
				}
			}
		}
	}
}

// At its limit nothing runs away: DC either sign and sines from 20 Hz to 20 kHz, 3 s each, at every design
// (a DSD source's at Limit, a PCM source's at LimitPCM).
func TestLoopStableAtLimit(t *testing.T) {
	for _, src := range sources {
		lim := limitFor(src)
		for _, kind := range []string{"standard", "clans"} {
			for fam := 0; fam < 2; fam++ {
				for _, f := range []float64{0, 20, 1000, 10000, 20000} {
					for _, a := range []float64{lim, -lim} {
						if f > 0 && a < 0 {
							continue
						}
						if r, _ := runs(tableFor(src)[kind][fam], families[fam].rate, f, a, 3); r != 0 {
							t.Errorf("%s %s %d: %d runaways at %.0f Hz, %.2f", src, kind, fam, r, f, a)
						}
					}
				}
			}
		}
	}
}

// A loop that does run away (a gain of 3: unstable at any level) is cleared and keeps going: resets
// counted, no NaN, and the bits still follow the input.
func TestRunawayIsCleared(t *testing.T) {
	bad := five(designStandard(order, 2*math.Pi*20000/2822400, 3).sections())
	r, bits := runs(bad, 2822400, 0, 0.3, 0.5)
	if r == 0 {
		t.Fatal("no runaway counted for a design that cannot be stable")
	}
	ones := 0
	for _, b := range bits {
		ones += int(b)
	}
	if mean := float64(ones)/float64(len(bits))*2 - 1; mean < 0 {
		t.Errorf("mean %.3f for a DC of 0.3: the output stopped following the input", mean)
	}
}

